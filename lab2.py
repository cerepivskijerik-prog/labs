scores = [67, 82, 45, 91, 76, 88, 54]
maximum = scores[0]

print("score | maximum до | score > maximum | maximum после")

for score in scores:
    maximum_before = maximum

    if score > maximum:
        maximum = score

    print(
        score, "|",
        maximum_before, "|",
        score > maximum_before, "|",
        maximum
    )

print("Максимальное значение:", maximum)


