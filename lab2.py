numbers = [-4, 7, -2, 10, 5, -8]

# Императивный стиль: состояние total изменяется явно.
total = 0

for number in numbers:
    if number > 0:
        total = total + number

print("Императивный вариант:", total)

# Декларативная запись:
declarative_total = sum(number for number in numbers if number > 0)
print("Более декларативный вариант:", declarative_total)

