print("\n" + "=" * 60)
print("ИНДИВИДУАЛЬНОЕ ЗАДАНИЕ № 1. БАНКОВСКИЙ СЧЕТ")
print("=" * 60)

balance = float(input("Введите текущий баланс: "))
withdrawal = float(input("Введите сумму снятия: "))

if withdrawal <= 0:
    print("Ошибка: сумма снятия должна быть больше нуля.")
elif withdrawal <= balance:
    balance = balance - withdrawal
    print("Снятие выполнено успешно.")
    print("Новый баланс:", balance)
else:
    print("Недостаточно средств.")
    print("Баланс не изменен:", balance)


