# ЗАДАНИЕ 4. Накопление состояния в цикле
# ============================================================

print("\n" + "=" * 60)
print("ЗАДАНИЕ 4. НАКОПЛЕНИЕ СОСТОЯНИЯ")
print("=" * 60)

numbers = [12, -5, 8, -3, 21, 0, 14, -7]

total = 0
positive_sum = 0
positive_count = 0
negative_count = 0
zero_count = 0

print("Изменение переменных на каждой итерации:")

for number in numbers:
    total = total + number

    if number > 0:
        positive_sum = positive_sum + number
        positive_count = positive_count + 1
    elif number < 0:
        negative_count = negative_count + 1
    else:
        zero_count = zero_count + 1

    print(
        "Число:", number,
        "| total:", total,
        "| positive_sum:", positive_sum,
        "| positive_count:", positive_count,
        "| negative_count:", negative_count,
        "| zero_count:", zero_count
    )

print("Сумма всех чисел:", total)
print("Сумма положительных чисел:", positive_sum)
print("Количество положительных:", positive_count)
print("Количество отрицательных:", negative_count)
print("Количество нулей:", zero_count)


